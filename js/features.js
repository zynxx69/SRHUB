/* ==========================================================================
   STUDENT REPUBLIC - EXTRA FEATURES  (js/features.js)
   Menu drawer, notifications, 3D motion, holder credit, view counter.
   You normally do NOT edit this file. Change content in js/draftsr.js instead.
   Sections: 1 Menu | 2 Notifications | 3 3D motion | 4 Holder + counter
   ========================================================================== */
document.addEventListener("DOMContentLoaded", () => {
  const $  = (s, c = document) => c.querySelector(s);
  const $$ = (s, c = document) => Array.from(c.querySelectorAll(s));
  const reduce = matchMedia("(prefers-reduced-motion: reduce)").matches;
  const esc = s => String(s ?? "").replace(/[&<>"]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
  const SR = window.SR || { allEvents: [], getStatus: () => "past" };      // exposed by sr.js
  const track = (path, title) => window.goatcounter && window.goatcounter.count && window.goatcounter.count({ path, title, event: true });

  /* ---------------- 1) MENU DRAWER (three-line button) ---------------- */
  const burger = $("#nav-toggle"), drawer = $("#drawer"), scrim = $("#scrim");
  function setDrawer(open) {
    drawer.classList.toggle("open", open); scrim.classList.toggle("open", open);
    burger.classList.toggle("is-open", open); burger.setAttribute("aria-expanded", String(open));
    document.body.classList.toggle("lock", open);
    if (open) setPanel(false);
  }
  burger.addEventListener("click", () => setDrawer(!drawer.classList.contains("open")));
  scrim.addEventListener("click", () => setDrawer(false));
  $("#drawer-close").addEventListener("click", () => setDrawer(false));
  drawer.addEventListener("click", e => { if (e.target.closest("a")) setDrawer(false); });

  /* ---------------- 2) NOTIFICATIONS ---------------- */
  // Settings live in js/draftsr.js (NOTIFICATION_SETTINGS, ANNOUNCEMENTS, SECURITY_NOTICE)
  const NS = typeof NOTIFICATION_SETTINGS !== "undefined" ? NOTIFICATION_SETTINGS : { remindDaysBefore: 3, showOngoing: true, toastDelayMs: 5200 };
  const NEWS = typeof ANNOUNCEMENTS !== "undefined" ? ANNOUNCEMENTS : [];
  const NOTICE = typeof SECURITY_NOTICE !== "undefined" ? SECURITY_NOTICE : "";
  const bell = $("#bell"), panel = $("#notif-panel"), badge = $("#bell-count"), toastEl = $("#toast");
  let seen = false, toasted = false;

  function buildNotifications() {
    const now = new Date(), items = [];
    const day0 = d => new Date(d.getFullYear(), d.getMonth(), d.getDate());
    SR.allEvents.forEach(e => {
      const st = SR.getStatus(e);
      if (st === "ongoing" && NS.showOngoing) {
        items.push({ type: "live", t: -1, title: `${e.title} is currently being held`, text: e.location || "", target: e.title });
      } else if (st === "upcoming") {
        const left = Math.round((day0(e.startDate) - day0(now)) / 864e5);
        if (left <= NS.remindDaysBefore) {
          const when = left === 0 ? "starts today" : `starts in ${left} day${left > 1 ? "s" : ""}`;
          items.push({ type: "soon", t: left, title: `${e.title} ${when}`, text: SR.fmtDateRange(e.startDate, e.endDate).replace(/&middot;/g, "-").replace(/&ndash;/g, "to"), target: e.title });
        }
      }
    });
    NEWS.filter(a => a.active !== false).forEach(a => items.push({ type: "news", t: 99, title: a.title, text: a.message, link: a.link }));
    return items.sort((a, b) => a.t - b.t);
  }

  let current = [];
  function renderNotifications() {
    current = buildNotifications();
    const real = current.length;
    badge.hidden = seen || !real; badge.textContent = real;
    bell.classList.toggle("has", real > 0 && !seen);
    panel.innerHTML = `<div class="n-head"><h3>Notifications</h3><small>Tap one to open it</small></div>`
      + (real ? current.map((n, i) => `<button class="n-item n-${n.type}" data-i="${i}"><b>${esc(n.title)}</b>${n.text ? `<span>${esc(n.text)}</span>` : ""}<em>Tap to view</em></button>`).join("")
                : `<p class="n-empty">No event reminders right now.</p>`)
      + (NOTICE ? `<div class="n-item n-notice"><b>Notice</b><span>${esc(NOTICE)}</span></div>` : "");
  }
  function setPanel(open) { panel.classList.toggle("open", open); if (open) { seen = true; renderNotifications(); } }
  bell.addEventListener("click", e => { e.stopPropagation(); setDrawer(false); setPanel(!panel.classList.contains("open")); });
  panel.addEventListener("click", e => {
    e.stopPropagation();
    const b = e.target.closest("[data-i]"); if (!b) return;
    const n = current[+b.dataset.i]; setPanel(false); track("click/notification", n.title);
    if (n.target) goToEvent(n.target); else if (n.link && $(n.link)) $(n.link).scrollIntoView({ behavior: reduce ? "auto" : "smooth" });
  });
  document.addEventListener("click", () => setPanel(false));
  addEventListener("keydown", e => { if (e.key === "Escape") { setPanel(false); setDrawer(false); } });

  function goToEvent(title) {                     // scroll to the event card (or the calendar) and glow it
    const card = $$(".event-card[data-event]").find(c => c.dataset.event === title);
    (card || $("#calendar")).scrollIntoView({ behavior: reduce ? "auto" : "smooth", block: "center" });
    if (card) { card.classList.remove("flash"); void card.offsetWidth; card.classList.add("flash"); }
  }
  function toast(msg) { toastEl.textContent = msg; toastEl.classList.add("show"); setTimeout(() => toastEl.classList.remove("show"), 6000); }

  renderNotifications(); setInterval(renderNotifications, 60000);
  if (!toasted) {                                  // pop-up reminders shortly after the welcome screen
    toasted = true; const t0 = reduce ? 800 : NS.toastDelayMs;
    const first = current[0];
    if (first && first.type !== "news") setTimeout(() => toast(first.title), t0);
    if (NOTICE) setTimeout(() => toast(NOTICE), first ? t0 + 7000 : t0);
  }

  /* ---------------- 3) 3D MOTION (mouse, phone tilt, scroll, card tilt, click ripple) ---------------- */
  const stage = $(".seal-stage"), bar = $("#progress");
  const M = { tx: 0, ty: 0, cx: 0, cy: 0 };
  const clamp = (v, a = -1, b = 1) => Math.min(b, Math.max(a, v));
  if (!reduce) {
    addEventListener("pointermove", e => { if (e.pointerType !== "touch") { M.tx = (e.clientX / innerWidth - .5) * 2; M.ty = (e.clientY / innerHeight - .5) * 2; } }, { passive: true });
    const onTilt = e => { if (e.gamma != null) { M.tx = clamp(e.gamma / 30); M.ty = clamp(((e.beta || 45) - 45) / 30); } };
    if (window.DeviceOrientationEvent) {
      if (typeof DeviceOrientationEvent.requestPermission === "function") {       // iPhone: asks once, on first tap
        addEventListener("click", () => DeviceOrientationEvent.requestPermission().then(r => { if (r === "granted") addEventListener("deviceorientation", onTilt); }).catch(() => {}), { once: true });
      } else addEventListener("deviceorientation", onTilt);
    }
    addEventListener("pointerdown", e => {                                         // soft gold ripple on every tap
      const r = document.createElement("i"); r.className = "ripple";
      r.style.left = e.clientX + "px"; r.style.top = e.clientY + "px"; document.body.appendChild(r); setTimeout(() => r.remove(), 750);
    }, { passive: true });
    if (matchMedia("(hover: hover)").matches) {                                    // desktop: cards tilt toward the cursor
      document.addEventListener("pointermove", e => {
        const c = e.target.closest && e.target.closest(".event-card"); if (!c) return;
        const r = c.getBoundingClientRect();
        c.style.setProperty("--ty", ((e.clientX - r.left) / r.width - .5) * 12 + "deg");
        c.style.setProperty("--tx", -((e.clientY - r.top) / r.height - .5) * 12 + "deg");
        c.classList.add("tilting");
      }, { passive: true });
      document.addEventListener("pointerout", e => {
        const c = e.target.closest && e.target.closest(".event-card");
        if (c && !c.contains(e.relatedTarget)) { c.style.setProperty("--tx", "0deg"); c.style.setProperty("--ty", "0deg"); c.classList.remove("tilting"); }
      });
    }
  }
  (function loop() {                                                               // one smooth loop: values glide, never jump
    M.cx += (M.tx - M.cx) * .08; M.cy += (M.ty - M.cy) * .08;
    if (stage) { stage.style.setProperty("--ry", (M.cx * 18).toFixed(2) + "deg"); stage.style.setProperty("--rx", (M.cy * -14).toFixed(2) + "deg"); }
    const max = document.documentElement.scrollHeight - innerHeight;
    bar.style.transform = `scaleX(${max > 0 ? scrollY / max : 0})`;
    requestAnimationFrame(loop);
  })();

  /* ---------------- 4) WEBSITE HOLDER + VIEW COUNTER ---------------- */
  if (typeof SITE_HOLDER !== "undefined") {
    $$("[data-holder=name]").forEach(el => el.textContent = SITE_HOLDER.name);
    $$("[data-holder=short]").forEach(el => el.textContent = SITE_HOLDER.deptShort);
    $$("[data-holder=full]").forEach(el => el.textContent = SITE_HOLDER.deptFull);
  }
  const A = typeof ANALYTICS !== "undefined" ? ANALYTICS : {};
  if (A.goatcounterCode) {                                                          // free, privacy-friendly visit counter
    const s = document.createElement("script");
    s.async = true; s.src = "https://gc.zgo.at/count.js";
    s.dataset.goatcounter = `https://${A.goatcounterCode}.goatcounter.com/count`;
    document.head.appendChild(s);
    if (A.showPublicCount) {
      fetch(`https://${A.goatcounterCode}.goatcounter.com/counter/TOTAL.json`).then(r => r.json())
        .then(j => { $("#view-count").textContent = j.count; $("#view-count-wrap").hidden = false; }).catch(() => {});
    }
    document.addEventListener("click", e => { const a = e.target.closest("a[href*='facebook.com']"); if (a) track("click/facebook", "Facebook link"); });
  }
});
